import { useState, useMemo } from "react"
import HeaderTemplate from "@/components/common/PageTemplate"
import SearchTemplate from "@/components/common/SearchTemplate"
import { Card, CardContent, CardHeader, CardTitle, CardDescription } from "@/components/ui/card"
import { Switch } from "@/components/ui/switch"
import { Button } from "@/components/ui/button"
import { Input } from "@/components/ui/input"
import { toast } from "@/components/ui/toast"
import { Avatar, AvatarFallback, AvatarImage } from "@/components/ui/avatar"
import { Badge } from "@/components/ui/badge"
import {
  Dialog,
  DialogContent,
  DialogHeader,
  DialogTitle,
  DialogDescription,
} from "@/components/ui/dialog"
import {
  DropdownMenu,
  DropdownMenuContent,
  DropdownMenuItem,
  DropdownMenuTrigger,
} from "@/components/ui/dropdown-menu"
import {
  Accordion,
  AccordionItem,
  AccordionTrigger,
  AccordionContent,
} from "@/components/ui/accordion"
import { instructors, learners, type UserProps } from "@/const/data"
import { ArrowUpRight, Save, RotateCcw, UserPlus, Trash2, Search } from "lucide-react"

interface PermissionItem {
  id: string
  title: string
  description: string
  enabled: boolean
}

const initialInstructorPermissions: PermissionItem[] = [
  {
    id: "inst-1",
    title: "Create & Edit Course Modules",
    description: "Allows creation, editing, and publishing of lecture materials and modules",
    enabled: true,
  },
  {
    id: "inst-2",
    title: "Create Quizzes & Assessments",
    description: "Allows creating quizzes, grading student submissions, and managing rubrics",
    enabled: true,
  },
  {
    id: "inst-3",
    title: "Create & Manage Classrooms",
    description: "Allows creating classroom groups, managing enrolments, and posting announcements",
    enabled: true,
  },
  {
    id: "inst-4",
    title: "Run Accessibility Scanners",
    description: "Allows running WCAG 2.1 AA automated compliance scans on course content",
    enabled: true,
  },
  {
    id: "inst-5",
    title: "View Learner Analytics & Progress",
    description: "Allows viewing student performance metrics, completion rates, and test scores",
    enabled: true,
  },
  {
    id: "inst-6",
    title: "Invite Co-Instructors & TAs",
    description: "Allows sending invitation links to add additional instructors or teaching assistants",
    enabled: false,
  },
]

const initialLearnerPermissions: PermissionItem[] = [
  {
    id: "learn-1",
    title: "Use Aria AI Learning Assistant",
    description: "Allows asking Aria AI questions, generating study summaries, and getting instant assistance",
    enabled: true,
  },
  {
    id: "learn-2",
    title: "Use Accessibility Analyzer",
    description: "Allows running self-service accessibility checks on submitted work",
    enabled: true,
  },
  {
    id: "learn-3",
    title: "Join Classrooms & View Modules",
    description: "Allows enrolling in classrooms, accessing course content, and viewing learning modules",
    enabled: true,
  },
  {
    id: "learn-4",
    title: "Submit Assessments & Quizzes",
    description: "Allows submitting quiz answers and assessment work for instructor grading",
    enabled: true,
  },
  {
    id: "learn-5",
    title: "Export Technical Audit Reports",
    description: "Allows downloading WCAG accessibility audit reports generated by the scanner",
    enabled: false,
  },
]

export default function Permissions() {
  const [search, setSearch] = useState("")

  // Role Default Permissions & Saved Baseline State
  const [instructorPerms, setInstructorPerms] = useState<PermissionItem[]>(
    initialInstructorPermissions
  )
  const [savedInstructorPerms, setSavedInstructorPerms] = useState<PermissionItem[]>(
    initialInstructorPermissions
  )

  const [learnerPerms, setLearnerPerms] = useState<PermissionItem[]>(
    initialLearnerPermissions
  )
  const [savedLearnerPerms, setSavedLearnerPerms] = useState<PermissionItem[]>(
    initialLearnerPermissions
  )

  // Track user IDs that have active user-specific overrides
  const [instructorOverrideIds, setInstructorOverrideIds] = useState<string[]>([
    "inst-1",
    "inst-2",
  ])
  const [learnerOverrideIds, setLearnerOverrideIds] = useState<string[]>([
    "1234-1234",
    "1233-1233",
    "1235-1235",
    "1236-1236",
    "1237-1237",
    "1238-1238",
  ])

  // Per-User Custom Overrides Permissions State
  const [userOverrides, setUserOverrides] = useState<Record<string, PermissionItem[]>>({})

  // Dialog State (Locking dialogRole prevents data flashing on close)
  const [dialogOpen, setDialogOpen] = useState(false)
  const [dialogRole, setDialogRole] = useState<"instructor" | "learner">("instructor")

  // Search states within Dialog
  const [dialogUserSearch, setDialogUserSearch] = useState("")
  const [addUserSearch, setAddUserSearch] = useState("")

  // Check if un-saved changes exist for each role
  const isInstructorChanged = useMemo(() => {
    return JSON.stringify(instructorPerms) !== JSON.stringify(savedInstructorPerms)
  }, [instructorPerms, savedInstructorPerms])

  const isLearnerChanged = useMemo(() => {
    return JSON.stringify(learnerPerms) !== JSON.stringify(savedLearnerPerms)
  }, [learnerPerms, savedLearnerPerms])

  // Permission toggles for role defaults
  function toggleInstructorPerm(id: string, checked: boolean) {
    setInstructorPerms((prev) =>
      prev.map((item) => (item.id === id ? { ...item, enabled: checked } : item))
    )
  }

  function toggleLearnerPerm(id: string, checked: boolean) {
    setLearnerPerms((prev) =>
      prev.map((item) => (item.id === id ? { ...item, enabled: checked } : item))
    )
  }

  // Save / Discard Handlers
  function handleSaveInstructor() {
    setSavedInstructorPerms(instructorPerms)
    toast.add({
      title: "Instructor Permissions Saved",
      description: "Default permission matrix for instructors has been updated successfully.",
      type: "success",
    })
  }

  function handleDiscardInstructor() {
    setInstructorPerms(savedInstructorPerms)
    toast.add({
      title: "Changes Discarded",
      description: "Instructor permissions reverted to saved settings.",
    })
  }

  function handleSaveLearner() {
    setSavedLearnerPerms(learnerPerms)
    toast.add({
      title: "Learner Permissions Saved",
      description: "Default permission matrix for learners has been updated successfully.",
      type: "success",
    })
  }

  function handleDiscardLearner() {
    setLearnerPerms(savedLearnerPerms)
    toast.add({
      title: "Changes Discarded",
      description: "Learner permissions reverted to saved settings.",
    })
  }

  // Dialog Open Handler
  function openRoleDialog(role: "instructor" | "learner") {
    setDialogRole(role)
    setDialogUserSearch("")
    setAddUserSearch("")
    setDialogOpen(true)
  }

  // User Overrides Helpers
  function getUserPermissions(userId: string, role: "instructor" | "learner"): PermissionItem[] {
    if (userOverrides[userId]) {
      return userOverrides[userId]
    }
    return role === "instructor" ? instructorPerms : learnerPerms
  }

  function toggleUserOverride(
    userId: string,
    permId: string,
    checked: boolean,
    role: "instructor" | "learner"
  ) {
    const current = getUserPermissions(userId, role)
    const updated = current.map((p) => (p.id === permId ? { ...p, enabled: checked } : p))
    setUserOverrides((prev) => ({
      ...prev,
      [userId]: updated,
    }))
  }

  function handleAddUserOverride(userId: string, role: "instructor" | "learner") {
    if (role === "instructor") {
      if (!instructorOverrideIds.includes(userId)) {
        setInstructorOverrideIds((prev) => [...prev, userId])
      }
    } else {
      if (!learnerOverrideIds.includes(userId)) {
        setLearnerOverrideIds((prev) => [...prev, userId])
      }
    }
    setAddUserSearch("")
    const targetUser = [...instructors, ...learners].find((u) => u.id === userId)
    toast.add({
      title: "User Override Added",
      description: `Added custom permission override for ${targetUser?.name || "user"}.`,
      type: "success",
    })
  }

  function handleRemoveUserOverride(userId: string, role: "instructor" | "learner") {
    if (role === "instructor") {
      setInstructorOverrideIds((prev) => prev.filter((id) => id !== userId))
    } else {
      setLearnerOverrideIds((prev) => prev.filter((id) => id !== userId))
    }
    setUserOverrides((prev) => {
      const next = { ...prev }
      delete next[userId]
      return next
    })
    const targetUser = [...instructors, ...learners].find((u) => u.id === userId)
    toast.add({
      title: "User Override Removed",
      description: `Removed custom permission override for ${targetUser?.name || "user"}.`,
    })
  }

  function getEmail(user: UserProps) {
    return `${user.name.toLowerCase().replace(/[^a-z0-9]/g, "")}@gmail.com`
  }

  function getInitials(name: string) {
    return name
      .split(" ")
      .map((part) => part[0])
      .join("")
      .slice(0, 2)
      .toUpperCase()
  }

  const query = search.toLowerCase().trim()

  const filteredInstructorPerms = instructorPerms.filter(
    (p) => p.title.toLowerCase().includes(query) || p.description.toLowerCase().includes(query)
  )

  const filteredLearnerPerms = learnerPerms.filter(
    (p) => p.title.toLowerCase().includes(query) || p.description.toLowerCase().includes(query)
  )

  // Override Users in Dialog
  const currentDialogOverrideUsers = useMemo(() => {
    const allRoleUsers = dialogRole === "instructor" ? instructors : learners
    const activeIds = dialogRole === "instructor" ? instructorOverrideIds : learnerOverrideIds
    return allRoleUsers.filter((u) => activeIds.includes(u.id))
  }, [dialogRole, instructorOverrideIds, learnerOverrideIds])

  // Filtered Override Users inside Dialog Search
  const filteredDialogOverrideUsers = useMemo(() => {
    if (!dialogUserSearch.trim()) return currentDialogOverrideUsers
    const q = dialogUserSearch.toLowerCase().trim()
    return currentDialogOverrideUsers.filter(
      (u) => u.name.toLowerCase().includes(q) || getEmail(u).toLowerCase().includes(q)
    )
  }, [currentDialogOverrideUsers, dialogUserSearch])

  // Available users to add to overrides
  const availableUsersToAdd = useMemo(() => {
    const allRoleUsers = dialogRole === "instructor" ? instructors : learners
    const activeIds = dialogRole === "instructor" ? instructorOverrideIds : learnerOverrideIds
    return allRoleUsers.filter((u) => !activeIds.includes(u.id))
  }, [dialogRole, instructorOverrideIds, learnerOverrideIds])

  // Filtered available users by search in Add User dropdown
  const filteredAvailableUsersToAdd = useMemo(() => {
    if (!addUserSearch.trim()) return availableUsersToAdd
    const q = addUserSearch.toLowerCase().trim()
    return availableUsersToAdd.filter(
      (u) => u.name.toLowerCase().includes(q) || getEmail(u).toLowerCase().includes(q)
    )
  }, [availableUsersToAdd, addUserSearch])

  return (
    <section className="p-responsive space-y-6">
      {/* Header */}
      <HeaderTemplate
        title="Permission Management"
        subtitle="Configure default role permissions and manage granular user access overrides"
      />

      {/* Search Input */}
      <div className="max-w-md">
        <SearchTemplate
          search={search}
          setSearch={setSearch}
          title="permissions"
        />
      </div>

      {/* Instructor Role Permissions */}
      <Card className="p-6">
        <CardHeader className="p-0 pb-4">
          <CardTitle className="text-lg sm:text-xl font-bold">
            Instructor Role Permissions
          </CardTitle>
          <CardDescription className="text-sm text-muted-foreground">
            Default permission matrix applied to all instructor accounts
          </CardDescription>
        </CardHeader>

        <CardContent className="p-0 space-y-3">
          {filteredInstructorPerms.length === 0 ? (
            <div className="p-4 text-sm text-muted-foreground border border-dashed rounded-xl text-center">
              No instructor permissions matching "{search}".
            </div>
          ) : (
            filteredInstructorPerms.map((item) => (
              <div
                key={item.id}
                className="flex items-center justify-between gap-4 rounded-xl bg-muted/40 p-4 transition-colors hover:bg-muted/60"
              >
                <div className="space-y-0.5">
                  <h4 className="font-medium text-foreground text-sm sm:text-base">
                    {item.title}
                  </h4>
                  <p className="text-xs sm:text-sm text-muted-foreground">
                    {item.description}
                  </p>
                </div>
                <Switch
                  checked={item.enabled}
                  onCheckedChange={(checked) => toggleInstructorPerm(item.id, checked)}
                />
              </div>
            ))
          )}

          {/* User-Specific Overrides row */}
          <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 rounded-xl bg-muted/40 p-4">
            <div className="space-y-0.5">
              <h4 className="font-medium text-foreground text-sm sm:text-base">
                User-Specific Overrides
              </h4>
              <p className="text-xs sm:text-sm text-muted-foreground">
                Grant or revoke specific permissions for individual users, overriding their default role settings
              </p>
            </div>
            <Button
              variant="ghost"
              size="sm"
              onClick={() => openRoleDialog("instructor")}
              className="w-fit self-start sm:self-auto font-medium text-xs sm:text-sm shrink-0"
            >
              ({instructorOverrideIds.length}) View List <ArrowUpRight className="ml-1 h-3.5 w-3.5" />
            </Button>
          </div>

          {/* Bottom Card Actions (only appear if changes exist) */}
          {isInstructorChanged && (
            <div className="flex items-center justify-end gap-3 pt-4 transition-all">
              <Button variant="outline" onClick={handleSaveInstructor}>
                <Save className="mr-1.5 h-4 w-4" />
                Save Changes
              </Button>
              <Button
                className="bg-zinc-900 text-white hover:bg-zinc-800 dark:bg-zinc-100 dark:text-zinc-900 dark:hover:bg-zinc-200"
                onClick={handleDiscardInstructor}
              >
                <RotateCcw className="mr-1.5 h-4 w-4" />
                Discard Changes
              </Button>
            </div>
          )}
        </CardContent>
      </Card>

      {/* Learner Role Permissions */}
      <Card className="p-6">
        <CardHeader className="p-0 pb-4">
          <CardTitle className="text-lg sm:text-xl font-bold">
            Learner Role Permissions
          </CardTitle>
          <CardDescription className="text-sm text-muted-foreground">
            Default permission matrix applied to all enrolled student accounts
          </CardDescription>
        </CardHeader>

        <CardContent className="p-0 space-y-3">
          {filteredLearnerPerms.length === 0 ? (
            <div className="p-4 text-sm text-muted-foreground border border-dashed rounded-xl text-center">
              No learner permissions matching "{search}".
            </div>
          ) : (
            filteredLearnerPerms.map((item) => (
              <div
                key={item.id}
                className="flex items-center justify-between gap-4 rounded-xl bg-muted/40 p-4 transition-colors hover:bg-muted/60"
              >
                <div className="space-y-0.5">
                  <h4 className="font-medium text-foreground text-sm sm:text-base">
                    {item.title}
                  </h4>
                  <p className="text-xs sm:text-sm text-muted-foreground">
                    {item.description}
                  </p>
                </div>
                <Switch
                  checked={item.enabled}
                  onCheckedChange={(checked) => toggleLearnerPerm(item.id, checked)}
                />
              </div>
            ))
          )}

          {/* User-Specific Overrides row */}
          <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 rounded-xl bg-muted/40 p-4">
            <div className="space-y-0.5">
              <h4 className="font-medium text-foreground text-sm sm:text-base">
                User-Specific Overrides
              </h4>
              <p className="text-xs sm:text-sm text-muted-foreground">
                Grant or revoke specific permissions for individual users, overriding their default role settings
              </p>
            </div>
            <Button
              variant="ghost"
              size="sm"
              onClick={() => openRoleDialog("learner")}
              className="w-fit self-start sm:self-auto font-medium text-xs sm:text-sm shrink-0"
            >
              ({learnerOverrideIds.length}) View List <ArrowUpRight className="ml-1 h-3.5 w-3.5" />
            </Button>
          </div>

          {/* Bottom Card Actions (only appear if changes exist) */}
          {isLearnerChanged && (
            <div className="flex items-center justify-end gap-3 pt-4 transition-all">
              <Button variant="outline" onClick={handleSaveLearner}>
                <Save className="mr-1.5 h-4 w-4" />
                Save Changes
              </Button>
              <Button
                className="bg-zinc-900 text-white hover:bg-zinc-800 dark:bg-zinc-100 dark:text-zinc-900 dark:hover:bg-zinc-200"
                onClick={handleDiscardLearner}
              >
                <RotateCcw className="mr-1.5 h-4 w-4" />
                Discard Changes
              </Button>
            </div>
          )}
        </CardContent>
      </Card>

      {/* User Overrides Dialog (max-w-lg) */}
      <Dialog open={dialogOpen} onOpenChange={setDialogOpen}>
        <DialogContent className="max-w-lg sm:max-w-lg max-h-[85vh] flex flex-col p-6 gap-4">
          <DialogHeader className="flex flex-col sm:flex-row sm:items-center sm:justify-between gap-2">
            <div>
              <DialogTitle className="text-lg font-bold">
                {dialogRole === "instructor" ? "Instructor User Overrides" : "Learner User Overrides"}
              </DialogTitle>
              <DialogDescription className="text-xs sm:text-sm text-muted-foreground">
                Configure granular user-specific permission overrides for {dialogRole === "instructor" ? "instructors" : "learners"}.
              </DialogDescription>
            </div>

            {/* Add User to Overrides Dropdown Button */}
            <DropdownMenu>
              <DropdownMenuTrigger
                render={
                  <Button size="sm" variant="outline" className="w-fit shrink-0 mt-2 sm:mt-0">
                    <UserPlus className="mr-1.5 h-4 w-4" />
                    Add User
                  </Button>
                }
              />
              <DropdownMenuContent align="end" className="w-64 max-h-72 p-1 overflow-y-auto">
                {/* Search box inside Add User dropdown */}
                <div
                  className="p-1 border-b mb-1 sticky top-0 bg-popover z-10"
                  onClick={(e) => e.stopPropagation()}
                >
                  <div className="relative">
                    <Search className="absolute left-2 top-1/2 -translate-y-1/2 h-3.5 w-3.5 text-muted-foreground" />
                    <Input
                      placeholder="Search user to add..."
                      value={addUserSearch}
                      onChange={(e) => setAddUserSearch(e.target.value)}
                      className="h-7 pl-7 text-xs"
                      onClick={(e) => e.stopPropagation()}
                      onKeyDown={(e) => e.stopPropagation()}
                    />
                  </div>
                </div>

                {filteredAvailableUsersToAdd.length === 0 ? (
                  <div className="p-3 text-xs text-muted-foreground text-center">
                    {availableUsersToAdd.length === 0
                      ? "All users are currently in overrides."
                      : "No user found matching search."}
                  </div>
                ) : (
                  filteredAvailableUsersToAdd.map((user) => (
                    <DropdownMenuItem
                      key={user.id}
                      onClick={() => handleAddUserOverride(user.id, dialogRole)}
                      className="cursor-pointer py-1.5"
                    >
                      <Avatar size="sm" className="mr-2 size-6">
                        <AvatarImage src={user.img} alt={user.name} />
                        <AvatarFallback className="text-[10px]">{getInitials(user.name)}</AvatarFallback>
                      </Avatar>
                      <span className="truncate text-xs font-medium">{user.name}</span>
                    </DropdownMenuItem>
                  ))
                )}
              </DropdownMenuContent>
            </DropdownMenu>
          </DialogHeader>

          {/* Search box for filtering configured user overrides */}
          {currentDialogOverrideUsers.length > 0 && (
            <div className="relative">
              <Search className="absolute left-3 top-1/2 -translate-y-1/2 h-4 w-4 text-muted-foreground" />
              <Input
                placeholder="Search override users..."
                value={dialogUserSearch}
                onChange={(e) => setDialogUserSearch(e.target.value)}
                className="pl-9 h-9 text-xs sm:text-sm"
              />
            </div>
          )}

          <div className="flex-1 overflow-y-auto pr-1 py-1 space-y-2">
            {currentDialogOverrideUsers.length === 0 ? (
              <div className="flex flex-col items-center justify-center p-8 text-center border border-dashed rounded-xl space-y-2">
                <p className="text-sm font-medium text-foreground">No User Overrides Configured</p>
                <p className="text-xs text-muted-foreground">
                  Click 'Add User' above to grant or revoke specific permissions for individual users.
                </p>
              </div>
            ) : filteredDialogOverrideUsers.length === 0 ? (
              <div className="p-6 text-xs sm:text-sm text-center text-muted-foreground border border-dashed rounded-xl">
                No override users matching "{dialogUserSearch}".
              </div>
            ) : (
              <Accordion className="space-y-2">
                {filteredDialogOverrideUsers.map((user) => {
                  const userPerms = getUserPermissions(user.id, dialogRole)
                  return (
                    <AccordionItem
                      key={user.id}
                      value={user.id}
                      className="border rounded-xl px-4 py-1"
                    >
                      <div className="flex items-center justify-between w-full">
                        <AccordionTrigger className="hover:no-underline py-3 flex-1">
                          <div className="flex items-center gap-3">
                            <Avatar size="sm">
                              <AvatarImage src={user.img} alt={user.name} />
                              <AvatarFallback>{getInitials(user.name)}</AvatarFallback>
                            </Avatar>
                            <div className="text-left">
                              <div className="flex items-center gap-2">
                                <span className="font-medium text-foreground text-sm">
                                  {user.name}
                                </span>
                                <Badge variant="secondary" className="capitalize text-[10px] py-0 px-1.5">
                                  {user.role}
                                </Badge>
                              </div>
                              <span className="text-xs text-muted-foreground block">
                                {getEmail(user)}
                              </span>
                            </div>
                          </div>
                        </AccordionTrigger>

                        {/* Remove User from Overrides Button */}
                        <Button
                          variant="ghost"
                          size="icon-sm"
                          onClick={(e) => {
                            e.stopPropagation()
                            handleRemoveUserOverride(user.id, dialogRole)
                          }}
                          className="mr-2 text-muted-foreground hover:text-destructive shrink-0"
                          title="Remove user override"
                        >
                          <Trash2 className="h-4 w-4" />
                          <span className="sr-only">Remove user override</span>
                        </Button>
                      </div>

                      <AccordionContent className="pt-2 pb-3 space-y-2">
                        <p className="text-[11px] font-semibold text-muted-foreground uppercase tracking-wider mb-2">
                          Permission Toggles
                        </p>
                        {userPerms.map((perm) => (
                          <div
                            key={perm.id}
                            className="flex items-center justify-between gap-3 rounded-lg bg-muted/40 p-3 text-xs sm:text-sm"
                          >
                            <div className="space-y-0.5">
                              <p className="font-medium text-foreground">{perm.title}</p>
                              <p className="text-xs text-muted-foreground line-clamp-1">
                                {perm.description}
                              </p>
                            </div>
                            <Switch
                              size="sm"
                              checked={perm.enabled}
                              onCheckedChange={(checked) =>
                                toggleUserOverride(user.id, perm.id, checked, dialogRole)
                              }
                            />
                          </div>
                        ))}
                      </AccordionContent>
                    </AccordionItem>
                  )
                })}
              </Accordion>
            )}
          </div>
        </DialogContent>
      </Dialog>
    </section>
  )
}
